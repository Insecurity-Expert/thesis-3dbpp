"""The viewer's gap fields (optimizer/arrangement_view.gap_view) carry exactly
layout_metrics.face_gaps / gap_metrics (M-6), and the client's gap fixture is
built from them.

    python tools/test_layout_view.py           # checks
    python tools/test_layout_view.py --write   # regenerate the client fixture

The fixture (client/src/viewer/__fixtures__/gap_fixture.json) is the fixed
arrangement the client tests draw gap labels from; this test fails when it no
longer matches what arrangement_view produces.
"""
import sys
import json
from pathlib import Path

_ROOT = Path(__file__).resolve().parent.parent
sys.path[:0] = [str(_ROOT), str(_ROOT / 'optimizer'), str(_ROOT / 'experiments')]

from arrangement_view import wtpack_entry, gap_view, render_container_of   # noqa: E402
from layout_metrics import face_gaps, gap_metrics                          # noqa: E402

FIXTURE = _ROOT / 'client' / 'src' / 'viewer' / '__fixtures__' / 'gap_fixture.json'
STUDY = _ROOT / 'experiments' / 'results' / 'studies' / 'studyB_sample8_quick_s1-10_serial.json'
FAILS = []


def check(cond, msg):
    print(("  ok   " if cond else "  FAIL ") + msg)
    if not cond:
        FAILS.append(msg)


# A fixed arrangement (physics: x across, y depth from the door, z height) with
# box-box gaps in x and y, a stacked layer, door-side gaps of several depths
# (boxes 2 and 6 share one) and one unloaded box that sets tau = 20 cm.
CONTAINER = {'L': 100.0, 'W': 200.0, 'H': 90.0, 'door': 'rear'}
BOXES = [  # (placement, stop, mass)
    ((0, 150, 0, 40, 50, 30), 2, 20.0),
    ((60, 150, 0, 40, 50, 30), 2, 20.0),
    ((0, 150, 30, 40, 50, 30), 1, 5.0),
    ((0, 60, 0, 40, 40, 30), 1, 10.0),
    ((60, 100, 0, 40, 30, 30), 1, 10.0),
    (None, 1, 3.0),                       # not loaded: 20 x 25 x 30
    ((60, 150, 30, 40, 50, 30), 3, 5.0),  # stop 3 on top of a stop-2 box
]


def fixture():
    items, placements = [], {}
    for k, (p, stop, mass) in enumerate(BOXES):
        l, w, h = (p[3], p[4], p[5]) if p else (20, 25, 30)
        items.append({'id': str(k + 1), 'l': l, 'w': w, 'h': h, 'stop': stop, 'mass': mass, 'fragile': 0})
        if p:
            placements[k] = tuple(float(v) for v in p)
    entries = []
    for i, p in placements.items():
        e = wtpack_entry(items[i], i, p)
        e.update({'id': items[i]['id'], 'item_idx': i, 'bin_id': 0})
        entries.append(e)
    gaps = gap_view(entries, placements, CONTAINER, items)
    return {
        "note": "generated by tools/test_layout_view.py --write; do not edit",
        "container": render_container_of(CONTAINER),
        "items": entries,
        "gaps": gaps,
        "python_face_gaps": {str(i): g for i, g in face_gaps(placements, CONTAINER).items()},
        "python_gap_metrics": gap_metrics(placements, CONTAINER, items),
    }


def check_view(entries, placements, container, items, gaps, label):
    want = face_gaps(placements, container)
    check(all(abs(e['face_gaps'][f]['gap_cm'] - round(want[e['item_idx']][f], 4)) < 1e-9
              for e in entries for f in want[e['item_idx']]), f"{label}: every face gap equals face_gaps()")
    gm = gap_metrics(placements, container, items)
    check(all(gaps[k] == gm[k] for k in gm), f"{label}: run summary equals gap_metrics()")
    tau = gm['significant_threshold_cm']
    sig = sum(1 for e in entries for f in e['face_gaps'].values() if 'line' in f)
    check(sig == gm['significant_gaps'], f"{label}: one line per significant face gap ({sig})")
    P = {i: placements[i] for i in placements}
    ok_nb, ok_empty = True, True
    for e in entries:
        for name, f in e['face_gaps'].items():
            if f['to'] == 'box':
                ax = 'xyz'.index(name[0])
                i, j = e['item_idx'], f['box']
                pi, pj = P[i], P[j]
                d = (pj[ax] - (pi[ax] + pi[3 + ax])) if name[1] == '+' else (pi[ax] - (pj[ax] + pj[3 + ax]))
                ok_nb &= abs(d - f['gap_cm']) < 1e-6
            if 'block' in f and f['gap_cm'] > 0:
                b = f['block']
                for q in P.values():
                    if all(min(b[a] + b[3 + a], q[a] + q[3 + a]) - max(b[a], q[a]) > 1e-6 for a in range(3)):
                        ok_empty = False
            if 'line' in f:
                ok_empty &= f['gap_cm'] >= tau - 1e-9
    check(ok_nb, f"{label}: every 'box' neighbour sits exactly one gap beyond the face")
    check(ok_empty, f"{label}: every shaded empty block is empty and every drawn gap is significant")


def main():
    fx = fixture()
    if '--write' in sys.argv:
        FIXTURE.parent.mkdir(parents=True, exist_ok=True)
        FIXTURE.write_text(json.dumps(fx, indent=1) + "\n", encoding='utf-8')
        print(f"wrote {FIXTURE.relative_to(_ROOT)}")
    check(FIXTURE.exists() and json.loads(FIXTURE.read_text(encoding='utf-8')) == json.loads(json.dumps(fx)),
          "client gap fixture matches arrangement_view (regenerate with --write)")

    items = [{'l': (p[3] if p else 20), 'w': (p[4] if p else 25), 'h': (p[5] if p else 30), 'mass': m}
             for p, _, m in BOXES]
    pl = {k: tuple(float(v) for v in p) for k, (p, _, _) in enumerate(BOXES) if p}
    check_view(fx['items'], pl, CONTAINER, items, fx['gaps'], "fixture")
    check(fx['gaps']['significant_threshold_cm'] == 20.0, "fixture: tau = 20 cm from the unloaded box")
    g = {e['item_idx']: e['face_gaps'] for e in fx['items']}
    check(g[0]['x+']['gap_cm'] == 20 and g[0]['x+']['to'] == 'box' and g[0]['x+']['box'] == 1, "fixture: box 1 -> box 2 is 20 cm in x")
    check(g[3]['y-']['to'] == 'wall' and g[3]['y-']['gap_cm'] == 60, "fixture: box 4 is 60 cm from the door wall")
    check(g[0]['y-']['to'] == 'box' and g[0]['y-']['gap_cm'] == 50, "fixture: box 1 -> box 4 is 50 cm in y")

    if STUDY.exists():
        from run_view import run_view
        from preprocessing.pipeline import load_augmented_instance
        doc = json.loads(STUDY.read_text(encoding='utf-8'))
        for idx in (0, len(doc['runs']) - 1):
            run = doc['runs'][idx]
            v = run_view(str(STUDY), idx)
            inst = load_augmented_instance({'data': {'raw_dir': str(_ROOT / 'data' / 'raw')}},
                                           instance_id=run['instance_id'], stop_seed=doc['stop_seed'],
                                           stop_count=doc['stop_count'])
            pl = {int(k): tuple(float(x) for x in p) for k, p in run['placements'].items()}
            check_view(v['items'], pl, inst['container'], inst['boxes'], v['gaps'], f"study B run {idx}")
            check(v['container']['y_origin'] == 'door', f"study B run {idx}: container says where y = 0 is")

    print()
    if FAILS:
        print(f"FAIL ({len(FAILS)})")
        sys.exit(1)
    print("PASS - tools/test_layout_view.py")


if __name__ == '__main__':
    main()
